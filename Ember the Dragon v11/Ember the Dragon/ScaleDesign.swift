import Foundation

enum ScaleShape: String, CaseIterable, Codable { case leaf = "Leaf", diamond = "Diamond", round = "Pebble" }
struct ScaleDecoration: Codable, Equatable {
    let slot: Int
    let shape: ScaleShape
    let quarterTurns: Int
    var surfacePosition: SIMD3<Float>? = nil
    var surfaceNormal: SIMD3<Float>? = nil
    var finalPosition: SIMD3<Float>? = nil
    var finalNormal: SIMD3<Float>? = nil
    func position(complete: Bool = false) -> SIMD3<Float> { (complete ? finalPosition : surfacePosition) ?? surfacePosition ?? ScaleDesignLayout.position(slot,complete:complete) }
    func normal(complete: Bool = false) -> SIMD3<Float> { (complete ? finalNormal : surfaceNormal) ?? surfaceNormal ?? ScaleDesignLayout.normal(slot,complete:complete) }
}
enum ScaleDesignLayout {
    static let slotCount = 36
    static func angle(_ slot: Int) -> Float { Float(slot / 6) * .pi / 3 }
    // Surface samples from the supplied meshes; both forms preserve the same logical pattern.
    static func position(_ slot: Int, complete: Bool = false) -> SIMD3<Float> { (complete ? fullPositions : repairPositions)[slot] }
    static func normal(_ slot: Int, complete: Bool = false) -> SIMD3<Float> { (complete ? fullNormals : repairNormals)[slot] }
    static func valid(_ design: [ScaleDecoration]) -> Bool {
        Set(design.map(\.slot)).count == design.count && design.allSatisfy { item in
            guard (0..<4).contains(item.quarterTurns) else { return false }
            if let p = item.surfacePosition, let n = item.surfaceNormal { let vectors = [p,n,item.finalPosition ?? p,item.finalNormal ?? n]
                return vectors.allSatisfy { [$0.x,$0.y,$0.z].allSatisfy { $0.isFinite && abs($0)<2 } } && n.x*n.x+n.y*n.y+n.z*n.z > 0.25 }
            return (0..<slotCount).contains(item.slot)
        }
    }
    static func ready(_ design: [ScaleDecoration], gentle: Bool) -> Bool {
        design.count >= (gentle ? 6 : 9) && Set(design.map { $0.slot / 6 }).count >= (gentle ? 2 : 3)
    }

